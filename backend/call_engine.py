"""In-memory call lifecycle simulator.

This module simulates call-control state only. It does not implement SIP signaling,
RTP media, audio, registration on a real network, or interoperability with PBXs.
"""
from __future__ import annotations

from datetime import datetime, timezone
from threading import RLock
from uuid import uuid4
from typing import Any

ENDPOINTS = {
    "1001": {"extension": "1001", "display_name": "Demo Alice", "registered": True},
    "1002": {"extension": "1002", "display_name": "Demo Bob", "registered": True},
    "1003": {"extension": "1003", "display_name": "Demo Charlie", "registered": True},
}
_calls: dict[str, dict[str, Any]] = {}
_lock = RLock()


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _event(call: dict[str, Any], event_type: str, message: str) -> None:
    call["events"].append({
        "timestamp": _now(),
        "event": event_type,
        "state": call["state"],
        "message": message,
    })


def list_endpoints() -> list[dict[str, Any]]:
    return [dict(value) for value in ENDPOINTS.values()]


def list_calls() -> list[dict[str, Any]]:
    with _lock:
        return [{k: v for k, v in call.items() if k != "events"} for call in _calls.values()]


def get_call(call_id: str) -> dict[str, Any] | None:
    with _lock:
        call = _calls.get(call_id)
        return dict(call) if call else None


def get_events(call_id: str) -> list[dict[str, Any]] | None:
    with _lock:
        call = _calls.get(call_id)
        return list(call["events"]) if call else None


def create_call(from_extension: str, to_extension: str) -> dict[str, Any]:
    with _lock:
        if from_extension not in ENDPOINTS:
            raise ValueError(f"Unknown calling extension: {from_extension}")
        if to_extension not in ENDPOINTS:
            raise ValueError(f"Unknown called extension: {to_extension}")
        if from_extension == to_extension:
            raise ValueError("Calling and called extensions must be different")
        if not ENDPOINTS[from_extension]["registered"]:
            raise ValueError(f"Calling extension {from_extension} is not registered")
        if not ENDPOINTS[to_extension]["registered"]:
            raise ValueError(f"Called extension {to_extension} is not registered")

        call_id = f"CALL-{uuid4().hex[:10].upper()}"
        call = {
            "call_id": call_id,
            "from_extension": from_extension,
            "to_extension": to_extension,
            "state": "RINGING",
            "created_at": _now(),
            "answered_at": None,
            "ended_at": None,
            "media": {
                "mode": "SIMULATED",
                "rtp_detected": False,
                "note": "No RTP packets or audio are generated by this simulator.",
            },
            "events": [],
        }
        _event(call, "CALL_CREATED", f"{from_extension} called {to_extension}; destination is ringing")
        _calls[call_id] = call
        return dict(call)


def answer_call(call_id: str) -> dict[str, Any]:
    with _lock:
        call = _calls.get(call_id)
        if not call:
            raise KeyError(f"Call not found: {call_id}")
        if call["state"] != "RINGING":
            raise ValueError(f"Cannot answer call in state {call['state']}")
        call["state"] = "ESTABLISHED"
        call["answered_at"] = _now()
        _event(call, "CALL_ANSWERED", f"{call['to_extension']} answered the call")
        return dict(call)


def hangup_call(call_id: str) -> dict[str, Any]:
    with _lock:
        call = _calls.get(call_id)
        if not call:
            raise KeyError(f"Call not found: {call_id}")
        if call["state"] == "ENDED":
            raise ValueError("Call is already ended")
        previous_state = call["state"]
        call["state"] = "ENDED"
        call["ended_at"] = _now()
        _event(call, "CALL_ENDED", f"Call ended from previous state {previous_state}")
        return dict(call)


def reset_calls() -> None:
    """Test helper: clear in-memory calls."""
    with _lock:
        _calls.clear()
